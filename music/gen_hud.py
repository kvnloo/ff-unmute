"""Turn the score events and the measurements into Rust constants: hud/src/generated.rs.

Run from the workspace root after music/analyze.py:
    python3 -I music/gen_hud.py

hud stays dependency-free and the picture is synced at compile time. The text the agent
types uses the measured values from out/measured.json, not the score.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import score as S  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
EV = json.loads((ROOT / "out" / "events.json").read_text())["events"]
M = json.loads((ROOT / "out" / "measured.json").read_text())
OUT = ROOT / "hud" / "src" / "generated.rs"
FPS = 30


def times(kind):
    return [e["t"] for e in EV if e["kind"] == kind]


def frame(t):
    return int(round(t * FPS))


# ---- shots: one cut per bar, then per 2 beats, per beat, per 8th, a held beat, the ending ----
starts = [0.0, 2.0]  # bars 1-2
starts += [4.0 + k * 1.0 for k in range(4)]  # bars 3-4
starts += [8.0 + k * S.BEAT for k in range(8)]  # bars 5-6
starts += [12.0 + k * S.BEAT / 2 for k in range(6)]  # bar 7, beats 1-3
starts += [13.5, 14.0]  # bar 7 beat 4 (held), bar 8
shot_frames = [frame(t) for t in starts] + [frame(S.LENGTH)]

bleeps_56 = [b for b in M["blips"] if 8.0 <= b["t"] < 12.0]
texts = [
    "listening…",
    f"{M['sample_rate']} Hz · {M['channels']} ch",
    f"onset {M['first_kick']:.3f} s",
    f"kick {M['kick_hz']:.1f} Hz",
    f"tempo {M['tempo_bpm']:.1f} BPM",
    f"bass {M['bass_hz']:.1f} Hz",
    "clap on 2 · 4",
    "chord Dm",
    f"tokens {M['tokens']}",
    f"bleep {bleeps_56[0]['hz']:.0f} Hz" if bleeps_56 else "bleep",
    "chord E",
    f"centroid {M['centroid_hz'] / 1000:.1f} kHz",
    "gate x.xxx.xxx",
    f"{M['lufs']:.1f} LUFS",
    "denser",
    "faster",
    "brighter",
    "louder",
    "closer",
    "now",
    "",
    "✓ unmuted",
]
assert len(texts) == len(starts), (len(texts), len(starts))

# ---- the agent's log: what it measured, line by line, with the time it heard it ----
log = [
    (0.0, "› listen  out/pass/music.wav"),
    (0.4, f"  read   {M['sample_rate']} Hz  {M['channels']} ch  {M['seconds']:.3f} s"),
    (0.9, "  fft    1024  hann  30 fps"),
    (1.6, f"  peak   {M['peak_db']:+.2f} dBFS"),
]
for i, t in enumerate(M["kicks"]):
    if i < 4 or i % 4 == 0:
        log.append((t, f"  kick   {t:6.3f} s  {M['kick_hz']:.1f} Hz"))
log.append(
    (
        M["kicks"][3] + 0.05 if len(M["kicks"]) > 3 else 5.5,
        f"  tempo  {M['tempo_bpm']:.1f} BPM",
    )
)
log.append((4.3, f"  bass   {M['bass_hz']:.1f} Hz  (A1)"))
for b in M["blips"][::2]:
    log.append((b["t"], f"  bleep  {b['t']:6.3f} s  {b['hz']:.1f} Hz"))
for i, t in enumerate(times("token")):
    if i % 6 == 0:
        log.append((t, f"  token  #{i + 1:02d}  {t:6.3f} s"))
for t in times("clap")[:2]:
    log.append((t, f"  clap   {t:6.3f} s"))
for t in times("stutter"):
    log.append((t, f"  repeat {t:6.3f} s  4 × 1/32"))
log += [
    (11.9, f"  lufs   {M['lufs']:.1f}"),
    (12.6, f"  tp     {M['true_peak_db']:.1f} dBTP"),
    (13.4, "  build  denser, faster"),
    (14.0, "› impact 14.000 s"),
    (15.0, "› unmuted"),
]
log.sort(key=lambda x: x[0])


def arr(name, ty, vals, fmt):
    body = ", ".join(fmt(v) for v in vals)
    return f"pub const {name}: [{ty}; {len(vals)}] = [{body}];\n"


def f32(v):
    return f"{float(v):.4f}"


def rs_str(s):
    return json.dumps(s, ensure_ascii=False)


out = [
    "// @generated by music/gen_hud.py from out/events.json and out/measured.json. Do not edit.\n",
    "#![allow(clippy::all)]\n\n",
    f"pub const BPM: f32 = {S.BPM:.1f};\n",
    f"pub const LENGTH_FRAMES: usize = {frame(S.LENGTH)};\n",
    f"pub const IMPACT: f32 = {S.IMPACT_AT:.4f};\n",
    f"pub const KICK_HZ: f32 = {M['kick_hz']:.1f};\n",
    f"pub const BASS_HZ: f32 = {M['bass_hz']:.1f};\n",
    arr("SHOT_FRAMES", "usize", shot_frames, str),
    arr("SHOT_TEXT", "&str", texts, rs_str),
    "/// Kick times as measured on the kick stem (s).\n",
    arr("KICKS", "f32", M["kicks"], f32),
    arr("CLAPS", "f32", times("clap"), f32),
    arr("TOKENS", "f32", times("token"), f32),
    arr("STUTTERS", "f32", times("stutter"), f32),
    "/// Bleeps: time (s) and measured frequency of the strongest component (Hz).\n",
    arr(
        "BLEEPS",
        "(f32, f32)",
        [(b["t"], b["hz"]) for b in M["blips"]],
        lambda v: f"({f32(v[0])}, {f32(v[1])})",
    ),
    "/// Level per video frame, dBFS.\n",
    arr("RMS", "f32", M["rms_per_frame"][: frame(S.LENGTH)], lambda v: f"{v:.1f}"),
    "/// The agent's log: when it heard it (s), the line.\n",
    arr("LOG", "(f32, &str)", log, lambda v: f"({f32(v[0])}, {rs_str(v[1])})"),
]
OUT.write_text("".join(out))
print(
    f"wrote {OUT.relative_to(ROOT)}: {len(starts)} shots, {len(M['kicks'])} kicks, {len(M['blips'])} bleeps, "
    f"{len(times('token'))} tokens, {len(log)} log lines"
)
